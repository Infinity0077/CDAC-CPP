// Program 3: Addition with User Input
// Demonstrates: cin and cout with user interaction

#include<iostream>
using namespace std;

main()
{
    int a, b, c;
    cout << "Enter two numbers: ";
    cin >> a >> b;
    c = a + b;
    cout << "Addition = " << c;
}

/*
Sample Input:
10 5

Output:
Enter two numbers: Addition = 15
*/
